"""Regenerate all 14 reports/certificates and an exact replay summary."""
import json
import time
from pathlib import Path
import engine
from exercises import EXERCISES
from app import TrigProofApp

def main():
    root=Path(__file__).resolve().parent
    out=root/'examples';out.mkdir(exist_ok=True)
    rows=[]
    for index,(year,lhs,rhs) in enumerate(EXERCISES,1):
        started=time.perf_counter()
        result=engine.prove_identity(lhs,rhs,'Use full identity catalogue')
        cert=result.to_certificate()
        ok,reason=engine.verify_rotation_certificate(cert,result.lhs,result.rhs,result.domain_conditions)
        if result.status!='PROVED' or not ok:
            raise RuntimeError(f'{index}: {result.status}, {reason}')
        stem=f'spm_{index:02d}_{year}'
        (out/(stem+'.json')).write_text(json.dumps(cert,indent=2,ensure_ascii=False),encoding='utf-8')
        (out/(stem+'.md')).write_text(result.to_markdown(),encoding='utf-8')
        (out/(stem+'.txt')).write_text(TrigProofApp._format_result(None,result),encoding='utf-8')
        row={'exercise':index,'year':year,'lhs':lhs,'rhs':rhs,'status':result.status,
             'certificate_replay':ok,'seconds':round(time.perf_counter()-started,3)}
        rows.append(row)
        print(f'{index:02d} ({year}): PROVED / REPLAY VERIFIED',flush=True)
    (root/'SPM_VALIDATION.json').write_text(json.dumps(rows,indent=2),encoding='utf-8')
    summary=['# SPM 14 exercise validation — v0.7.1','',
             'Generated by `python validate_spm.py`. Every result has an SPM algebraic explanation, checked by the internal exact certificate verifier.',
             'The exercise list is test/UI data and is never imported by the proof backend.','',
             '| Exercise | Year | Result | Replay | Report |','|---|---|---|---|---|']
    for row in rows:
        i,y=row['exercise'],row['year']
        summary.append(f'| {i} | {y} | PROVED | VERIFIED | [Proof](examples/spm_{i:02d}_{y}.md) |')
    (root/'SPM_VALIDATION.md').write_text('\n'.join(summary)+'\n',encoding='utf-8')

if __name__=='__main__': main()
